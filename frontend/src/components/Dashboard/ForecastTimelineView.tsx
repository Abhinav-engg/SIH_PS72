import React, { useState } from 'react';
import { NowcastMap } from './NowcastMap';
import { TimeSlider } from './TimeSlider';
import { Calendar, Layers } from 'lucide-react';

export function ForecastTimelineView() {
  const [selectedMinute, setSelectedMinute] = useState<number>(0);
  const [mode, setMode] = useState<'all' | 'radar' | 'lightning'>('all');

  const timelineSteps = [
    { title: 'T = 0m (Current Scan)', min: 0 },
    { title: 'T + 15m (+15 min)', min: 15 },
    { title: 'T + 30m (+30 min)', min: 30 },
    { title: 'T + 60m (+1 hour)', min: 60 },
    { title: 'T + 90m (+1.5 hours)', min: 90 },
    { title: 'T + 120m (+2 hours)', min: 120 },
  ];

  return (
    <div className="flex flex-col h-full gap-3 p-4 overflow-y-auto bg-nowcast-bg text-nowcast-text">
      <div className="flex items-center justify-between pb-2 border-b border-nowcast-border">
        <div>
          <h2 className="text-base font-bold text-nowcast-text flex items-center gap-2">
            <Calendar className="w-4 h-4 text-nowcast-accent" />
            Predicted Spatio-Temporal Evolution (0 to 120 Min Lead Time)
          </h2>
          <p className="text-xs text-nowcast-textMuted mt-0.5">
            Synchronized 15-minute forecasting intervals generated by PyTorch UNet-ConvLSTM
          </p>
        </div>

        <div className="flex bg-nowcast-sidebar border border-nowcast-card rounded-lg p-1">
          <button
            onClick={() => setMode('radar')}
            className={`px-3 py-1 text-xs font-bold rounded transition-colors ${
              mode === 'radar'
                ? 'bg-nowcast-accent/20 text-nowcast-accent border border-nowcast-accent/30'
                : 'text-nowcast-textMuted hover:text-nowcast-text'
            }`}
          >
            Radar Core
          </button>
          <button
            onClick={() => setMode('lightning')}
            className={`px-3 py-1 text-xs font-bold rounded transition-colors ${
              mode === 'lightning'
                ? 'bg-nowcast-accent/20 text-nowcast-accent border border-nowcast-accent/30'
                : 'text-nowcast-textMuted hover:text-nowcast-text'
            }`}
          >
            Lightning Risk
          </button>
          <button
            onClick={() => setMode('all')}
            className={`px-3 py-1 text-xs font-bold rounded transition-colors ${
              mode === 'all'
                ? 'bg-nowcast-accent/20 text-nowcast-accent border border-nowcast-accent/30'
                : 'text-nowcast-textMuted hover:text-nowcast-text'
            }`}
          >
            Composite Both
          </button>
        </div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3 flex-1 min-h-[460px]">
        {timelineSteps.map((step) => {
          const isActive = selectedMinute === step.min;
          return (
            <div
              key={step.min}
              onClick={() => setSelectedMinute(step.min)}
              className={`bg-nowcast-sidebar border rounded-xl overflow-hidden flex flex-col min-h-[200px] cursor-pointer transition-all ${
                isActive
                  ? 'border-nowcast-accent shadow-[0_0_12px_rgba(204,255,0,0.18)]'
                  : 'border-nowcast-card hover:border-nowcast-border'
              }`}
            >
              <div className="bg-nowcast-card/70 px-3 py-1.5 border-b border-nowcast-card text-xs font-bold text-nowcast-text flex justify-between items-center">
                <span>{step.title}</span>
                {isActive && (
                  <span className="text-[10px] font-mono text-nowcast-accent bg-nowcast-accent/10 px-1.5 py-0.5 rounded">
                    Active
                  </span>
                )}
              </div>
              <div className="flex-1 relative pointer-events-none">
                <NowcastMap />
              </div>
            </div>
          );
        })}
      </div>

      <div className="shrink-0 mt-1">
        <TimeSlider currentMinute={selectedMinute} onChange={setSelectedMinute} />
      </div>
    </div>
  );
}
